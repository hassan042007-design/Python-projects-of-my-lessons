# all data in python is object -----------------------------------------------------------
print(10) # will write 10
print(type(10)) # will write type of opject
print(type(9)) # this type is integer 
print(type(99.9)) # this type is flaot
print(type("hello python")) # this type is string 
print(type([1, 2, 3, 4, 5,])) # this type is list
print(type((1, 2, 3, 4, 5,))) # this type is tuple
print(type({"one":1, "two" : 2, "three":3 })) # this type is dictionary
print(type(2==2)) # this type is boolean (true or false)
print(type(2==4)) # this type is boolean (true or false)








