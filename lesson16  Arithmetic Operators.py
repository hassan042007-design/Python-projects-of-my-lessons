# Arithmetic Operators-------------------------------------------------------------------------------------
# [+] Addition
# [-] Subtraction
# [*] Multiplication
# [/] Division
# [%] Modulus : num which subtract from majour num to give whole num
# [**] Exponent : num power of 
# [//] Floor division : neglect the remainder


#Addition 

print(10 + 30) # 40
print(-10 + 20) # 10
print(1 + 2.66) # 3.66
print(1.2 + 1.3) # 2.5

# subtraction

print(60 - 30) # 30
print(-30 - 20) # -50
print(-30 - -20) # -10
print(5.66 - 3.44) # 2.22

# Multiplication

print(10 * 3) # 30
print(5 + 10 * 100) # 1005
print((5 + 10) * 100) # 1500

# Division

print(100 / 20) # 5.0
print(int(100 / 20)) # 5

# Modulus

print(8 % 2) # 0
print(9 % 2) # 1 (must subtract 1 from 9 to give whole number)
print(14 % 4 ) 

# Exponent
print(2**5) # 32 (two power five)
print(2*2*2*2*2) # 32 (two power five)
print(5**4) # 625
print(2**32)
print(2**128)

# Floor division
print(120 // 20) # 6
print(122 // 20) # 6 (neglect the remainder)
print (140 // 7) # 20
print (144 // 7) # 20
